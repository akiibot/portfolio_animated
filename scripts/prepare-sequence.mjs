import { createHash } from 'node:crypto';
import { readFile, mkdir, copyFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
export function digestFrames(frames){const hash=createHash('sha256');hash.update('original-png-v1');for(const frame of frames){hash.update(String(frame.length)+':');hash.update(frame);}return hash.digest('hex').slice(0,12);}
export async function prepareSequence(root=process.cwd()){
 const sources=Array.from({length:144},(_,i)=>resolve(root,`public/sequence/frame_${String(i).padStart(3,'0')}_delay-0.055s.png`));
 const version=digestFrames(await Promise.all(sources.map(f=>readFile(f))));
 await mkdir(resolve(root,`public/sequence/${version}`),{recursive:true});await mkdir(resolve(root,`public/hero/${version}`),{recursive:true});
 await Promise.all(sources.map((source,i)=>copyFile(source,resolve(root,`public/sequence/${version}/frame_${String(i).padStart(3,'0')}.png`))));
 await copyFile(sources[0],resolve(root,`public/hero/${version}/poster.png`));
 await writeFile(resolve(root,'src/lib/sequence-manifest.ts'),`// Generated by npm run prepare:sequence. Original PNG bytes are preserved.\nexport const sequenceManifest={version:'${version}',frameCount:144,posterSrc:'/hero/${version}/poster.png',srcFor:(index:number)=>'/sequence/${version}/frame_'+String(index).padStart(3,'0')+'.png'};\n`);
 console.log(`Prepared 144 original PNGs and poster: ${version}`);
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href)await prepareSequence();
